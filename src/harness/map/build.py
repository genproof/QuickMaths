"""Build a proof tree against the workbench and dump its declaration map (see harness.map)."""
from __future__ import annotations

import json
import os
import shutil
import subprocess
from pathlib import Path

TEMPLATE_FILES = ("lakefile.toml", "lean-toolchain", "Challenge.lean", "Solution.lean", "WorkspaceTest.lean",
                  "holes.json", "config.json")

MAP_LEAN = """import {root}
open Lean

/-! Plan-vs-Lean map (generated by `leh map`): name, module, own sorry, sorry-dependent, reached by the final
theorem `{final}`, and the interface statement the declaration refutes (its type is `¬ …Statement`, else `-`), one
tab-separated line per declaration under `{root}`. -/

def planMap : MetaM Unit := do
  let env ← getEnv
  let final := `{final}
  let mut names : Array Name := #[]
  for (n, _) in env.constants.toList do
    if n.getRoot == `{root} then names := names.push n
  let set : NameSet := names.foldl (fun s n => s.insert n) {{}}
  let mut uses : Std.HashMap Name (Array Name) := {{}}
  let mut direct : NameSet := {{}}
  let mut refutes : Std.HashMap Name String := {{}}
  for n in names do
    let some ci := env.find? n | continue
    if let .app (.const neg _) (.const s _) := ci.type then
      if neg == ``Not && s.toString.endsWith "Statement" then refutes := refutes.insert n s.toString
    let used := ci.getUsedConstantsAsSet
    if used.contains ``sorryAx then direct := direct.insert n
    uses := uses.insert n (used.toArray.filter set.contains)
  let mut rev : Std.HashMap Name (Array Name) := {{}}
  for (n, us) in uses.toList do
    for u in us do rev := rev.insert u ((rev.getD u #[]).push n)
  let mut dep : NameSet := direct
  let mut work := direct.toList
  while !work.isEmpty do
    let n := work.head!; work := work.tail!
    for m in rev.getD n #[] do
      if !dep.contains m then dep := dep.insert m; work := m :: work
  let mut reach : NameSet := {{}}
  let mut todo := [final]
  while !todo.isEmpty do
    let n := todo.head!; todo := todo.tail!
    if reach.contains n then continue
    reach := reach.insert n
    for u in uses.getD n #[] do todo := u :: todo
  for n in names do
    let mod := match env.getModuleIdxFor? n with
      | some i => toString (env.header.moduleNames[i.toNat]!)
      | none => "?"
    let refuted := refutes.getD n "-"
    IO.println s!"{{n}}\\t{{mod}}\\t{{if direct.contains n then 1 else 0}}\\t{{if dep.contains n then 1 else 0}}\\t{{if reach.contains n then 1 else 0}}\\t{{refuted}}"

#eval planMap
"""


def map_lean(final: str, root: str = "Submission") -> str:
    return MAP_LEAN.format(final=final, root=root)


def default_final(template: Path, problem: str) -> str:
    """`Submission.<first hole>` from the problem's holes.json, else `Submission.<problem>`."""
    try:
        data = json.loads((template / "holes.json").read_text())
        holes = data.get("holes", data) if isinstance(data, dict) else data
        first = holes[0] if holes else None
        name = first.get("name") if isinstance(first, dict) else first
        if name:
            return name if str(name).startswith("Submission.") else f"Submission.{name}"
    except (OSError, ValueError, KeyError, IndexError, TypeError, AttributeError):
        pass
    return f"Submission.{problem}"


def prepare(tree: Path, problem: str, workbench: Path) -> Path:
    """Make TREE a Lake workspace of PROBLEM: template files and the benchmark manifest are copied when missing,
    and `.lake/packages` links to the workbench's built packages (read-only use; an existing link is kept)."""
    bench = workbench / "vendor/lean-eval"
    template = bench / "generated" / problem
    if not template.is_dir():
        raise SystemExit(f"no template {template}: is the workbench built (leh workbench)?")
    if not (tree / "Submission.lean").is_file():
        raise SystemExit(f"{tree} has no Submission.lean")
    for name in TEMPLATE_FILES:
        if (template / name).is_file() and not (tree / name).exists():
            shutil.copy2(template / name, tree / name)
    if not (tree / "lake-manifest.json").exists():
        shutil.copy2(bench / "lake-manifest.json", tree / "lake-manifest.json")
    packages = tree / ".lake" / "packages"
    if not packages.exists() and not packages.is_symlink():
        packages.parent.mkdir(parents=True, exist_ok=True)
        packages.symlink_to(bench / ".lake" / "packages")
    return template


def build(tree: Path, problem: str, workbench: Path, final: str | None = None, threads: int = 16,
          timeout: int = 7200) -> Path:
    """Build `Submission` in TREE and write TREE/map.tsv; returns its path."""
    template = prepare(tree, problem, workbench)
    final = final or default_final(template, problem)
    env = dict(os.environ, LEAN_NUM_THREADS=str(threads),
               PATH=f"{Path.home() / '.elan/bin'}:{os.environ.get('PATH', '')}")
    with (tree / "build.log").open("w") as log:
        rc = subprocess.run(["lake", "build", "Submission"], cwd=tree, env=env, stdout=log, stderr=subprocess.STDOUT,
                            timeout=timeout).returncode
    if rc:
        raise SystemExit(f"lake build failed (exit {rc}); see {tree / 'build.log'}")
    (tree / "PlanMap.lean").write_text(map_lean(final))
    out = tree / "map.tsv"
    with out.open("w") as stream, (tree / "map.err").open("w") as err:
        rc = subprocess.run(["lake", "env", "lean", "PlanMap.lean"], cwd=tree, env=env, stdout=stream, stderr=err,
                            timeout=timeout).returncode
    if rc:
        raise SystemExit(f"map failed (exit {rc}); see {tree / 'map.err'}")
    return out
